-- Esquema de la base de datos dbgestor (PostgreSQL 16).
-- Coincide con las entidades JPA del backend: las fechas se guardan como texto (VARCHAR)
-- porque los modelos las manejan como String.
-- Restricciones de seguridad e integridad (ver docs/DOCUMENTO-TECNICO.md, incidencia 11):
--   * contrasena solo acepta hashes BCrypt (CWE-256: no se guardan contrasenas en texto plano).
--   * correo unico y campos obligatorios NOT NULL (CWE-287 / CWE-20).
--   * llaves foraneas con ON DELETE CASCADE (CWE-1188: integridad referencial).

DROP TABLE IF EXISTS asignaciones;
DROP TABLE IF EXISTS comentarios;
DROP TABLE IF EXISTS tareas;
DROP TABLE IF EXISTS proyectos;
DROP TABLE IF EXISTS usuario;

CREATE TABLE usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    correo_electronico VARCHAR(255) NOT NULL,
    contrasena VARCHAR(255) NOT NULL,
    rol VARCHAR(255) NOT NULL,
    imagen_usuario VARCHAR(255),
    CONSTRAINT uk_usuario_correo UNIQUE (correo_electronico),
    CONSTRAINT chk_usuario_contrasena_bcrypt CHECK (contrasena ~ '^\$2[aby]\$[0-9]{2}\$.{53}$'),
    CONSTRAINT chk_usuario_rol CHECK (rol IN ('Estudiante', 'Docente'))
);

CREATE TABLE proyectos (
    id_proyecto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255),
    fecha_inicio VARCHAR(255),
    fecha_finalizacion VARCHAR(255),
    estado_proyecto VARCHAR(255),
    fondo VARCHAR(255)
);

CREATE TABLE tareas (
    id_tarea INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    descripcion VARCHAR(255),
    fecha_vencimiento VARCHAR(255),
    estado VARCHAR(255),
    lista VARCHAR(255),
    id_proyecto INTEGER NOT NULL,
    CONSTRAINT fk_tareas_proyectos FOREIGN KEY (id_proyecto) REFERENCES proyectos (id_proyecto) ON DELETE CASCADE
);

-- id_usuario en comentarios guarda el nombre de quien comenta (asi lo envia el frontend),
-- por eso no puede ser llave foranea hacia usuario.
CREATE TABLE comentarios (
    id_comentario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto_comentario VARCHAR(255) NOT NULL,
    fecha_hora VARCHAR(255),
    id_usuario VARCHAR(255),
    id_tarea INTEGER NOT NULL,
    CONSTRAINT fk_comentarios_tareas FOREIGN KEY (id_tarea) REFERENCES tareas (id_tarea) ON DELETE CASCADE
);

CREATE TABLE asignaciones (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    id_tarea INTEGER NOT NULL,
    fecha_asignacion VARCHAR(255),
    CONSTRAINT fk_asignaciones_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT fk_asignaciones_tareas FOREIGN KEY (id_tarea) REFERENCES tareas (id_tarea) ON DELETE CASCADE
);

CREATE INDEX tareas_proyecto_idx ON tareas (id_proyecto);
CREATE INDEX comentarios_tarea_idx ON comentarios (id_tarea);
CREATE INDEX asignaciones_usuario_idx ON asignaciones (id_usuario);
CREATE INDEX asignaciones_tarea_idx ON asignaciones (id_tarea);
